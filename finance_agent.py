"""
finance_agent.py — Independent Financial Validator
Audits the LangGraph output for mathematical accuracy, schema compliance,
and budget limits before dispatching to the Authorization Gateway.
"""
from typing import Dict, Any
from pydantic import ValidationError
from agent_states import FinalProposalSchema


class FinanceValidator:
    """
    Independent Financial Audit Engine.
    Enforces Separation of Duties by re-verifying the AI agent output
    before committing transactions to the database ledger.
    """

    @staticmethod
    def audit_transaction(ai_pipeline_state: Dict[str, Any]) -> Dict[str, Any]:
        print("\n [FINANCE AUDIT] Initiating final compliance & mathematical audit...")

        # 1. Extract raw payload generated by Logistics / LangGraph Pipeline
        proposal_data = ai_pipeline_state.get("final_json_payload")
        if not proposal_data:
            reason = "Missing final proposal payload in pipeline state."
            print(f"❌ [FINANCE AUDIT] REJECTED: {reason}")
            return {"status": "REJECTED", "reason": reason}

        try:
            # 2. Strict Schema Validation (Guarantees data types & required fields)
            proposal = FinalProposalSchema(**proposal_data)

            # 3. Independent Mathematical Recalculation
            material_cost = round(proposal.final_unit_price * proposal.tonnage, 2)
            expected_total = round(material_cost + proposal.freight_cost, 2)

            # Check for floating point discrepancies (allowing 0.05 INR rounding tolerance)
            if abs(expected_total - proposal.total_landed_cost) > 0.05:
                reason = (
                    f"Mathematical discrepancy detected! "
                    f"AI reported total = {proposal.total_landed_cost:,.2f}, "
                    f"independently recalculated total = {expected_total:,.2f}."
                )
                print(f"❌ [FINANCE AUDIT] REJECTED: {reason}")
                return {"status": "REJECTED", "reason": reason}

            # 4. Enforce Hard Budget Cap Integrity
            if proposal.total_landed_cost > proposal.budget_cap and proposal.is_compliant:
                reason = (
                    f"Critical Compliance Breach! Transaction cost ({proposal.total_landed_cost:,.2f}) "
                    f"exceeds budget cap ({proposal.budget_cap:,.2f}), but AI falsely marked it as compliant."
                )
                print(f"❌ [FINANCE AUDIT] REJECTED: {reason}")
                return {"status": "REJECTED", "reason": reason}

            # Build validated dictionary and preserve carrier telemetry + PostgreSQL column aliases
            validated = proposal.model_dump()
            validated["selected_carrier"] = proposal_data.get("selected_carrier", "FastFreight Logistics (Road)")
            validated["base_carrier_rate"] = proposal_data.get("base_carrier_rate", 4.50)
            validated["vendor_name"] = proposal.selected_supplier
            validated["total_tonnage"] = proposal.tonnage
            validated["negotiated_unit_price"] = proposal.final_unit_price

            # 5. Handle Escalation / Human-in-the-Loop Triggers
            if proposal.human_approval_required:
                print("⚠️ [FINANCE AUDIT] ESCALATED: Transaction requires human manager approval.")
                return {
                    "status": "ESCALATED",
                    "reason": "Human approval flagged during pipeline execution.",
                    "validated_data": validated
                }

            # 6. Audit Passed
            print("✓ [FINANCE AUDIT] PASSED: Payload is structurally, mathematically, and policy sound.")
            return {
                "status": "APPROVED",
                "validated_data": validated
            }

        except ValidationError as e:
            error_details = e.errors()[0] if e.errors() else {}
            reason = f"Schema validation failure: {error_details.get('msg', 'Invalid data format')}."
            print(f"❌ [FINANCE AUDIT] REJECTED: {reason}")
            return {"status": "REJECTED", "reason": reason}


